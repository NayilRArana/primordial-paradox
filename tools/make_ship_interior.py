def plank(v):
    t = Tile(CRE)
    joints = {0: (5, 12, 3, 9), 1: (11, 4, 9, 14), 2: (8, 2, 13, 5)}[v]
    for r in range(4):
        y0 = r * 4
        t.rect(0, y0 + 3, 15, y0 + 3, DGO)
        t.rect(joints[r], y0, joints[r], y0 + 2, DGO)
        t.px(joints[r] + 2, y0 + 1, BRN)
        t.px(joints[r] - 2, y0 + 1, BRN)
        for i in range(3):
            t.px(hsh(i, r, v + 3) % 14 + 1, y0 + 1 + (i % 2), DGO)
    if v == 2:
        for x, y in ((7, 6), (8, 6), (9, 6), (7, 7), (9, 7), (8, 5)):
            t.px(x, y, BRN)
        t.px(8, 7, DGO)
    return t


