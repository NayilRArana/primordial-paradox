def verify(rows, tiles):
    used = set()
    for (g, name, *_r), t in zip(rows, tiles):
        cols = {c for r in t.g for c in r if c is not None}
        used |= cols
        if any(c is None for r in t.g for c in r):
            raise SystemExit("tile %r %s is not opaque" % (g, name))
        if len(cols - {K}) > 3:
            raise SystemExit("tile %r %s has %d colours besides the backdrop: %s" % (g, name, len(cols - {K}), sorted(hex(c) for c in cols)))
    if len(used) > 25:
        raise SystemExit("the sheet spends %d colours, the cap is 25" % len(used))
    return sorted(used)


def make_sheet(rows):
    tiles = [r[4]() for r in rows]
    used = verify(rows, tiles)
    rws = (len(rows) + 15) // 16
    im = Image.new("RGBA", (16 * T, rws * T), (0, 0, 0, 0))
    for i, t in enumerate(tiles):
        for y in range(T):
            for x in range(T):
                im.putpixel(((i % 16) * T + x, (i // 16) * T + y), NES[t.g[y][x]] + (255,))
    return im, used, rws


def classes_doc(rows):
    cls = {}
    for i, (g, name, solid, trig, _p) in enumerate(rows):
        cls[g] = {"index": i, "name": name, "solid": bool(solid), "walkable": not solid, "trigger": bool(trig), "plane": "ground"}
    return {"format": 1, "kind": "tile_classes", "name": "ship_interior", "sheet": "assets/tiles/ship_interior/ship_interior_tiles.png",
            "columns": 16, "card": "SHIP-RESTYLE", "classes": cls}


def gml_block(rows):
    lines = [BEGIN,
             "/// The ship interior rows (the restyled ship_small and ship_cabin, SHIP-RESTYLE): gid is the class index in",
             "/// data\\tile_classes_ship_interior.json and every tile is opaque ground, so none lays anything under itself.",
             "/// tests\\test_ship_interior.py pins these rows to the class file.",
             "function pp_map_tile_rows_ship_interior() {",
             "    return ["]
    for i, (g, name, *_r) in enumerate(rows):
        lines.append('        { ch: "%s", gid: %d, plane: PP_TILE_PLANE_GROUND, group: "", under: -1 }%s  // %s'
                     % (g, i, "," if i < len(rows) - 1 else " ", name))
    lines += ["    ];", "}", END]
    return "\n".join(lines)


