def bookcase():
    t = Tile(K)
    cols = (RED, BLU, DGO)
    for r, y0 in enumerate((1, 6, 11)):
        x = 1
        while x < 15:
            w = 2 + hsh(x, r, 5) % 2
            c = cols[hsh(x, r, 9) % 3]
            h = 3 + hsh(r, x, 4) % 2
            t.rect(x, y0 + 4 - h, min(x + w - 1, 14), y0 + 3, c)
            x += w + 1 - (1 if hsh(x, r, 2) % 3 == 0 else 0)
    return t


def carpet(n=False, e=False, s=False, w=False):
    t = Tile(DRD)
    for cx, cy in ((4, 4), (12, 12)):
        for d in range(-3, 4):
            for ee in range(-3, 4):
                if abs(d) + abs(ee) == 3:
                    t.px(cx + d, cy + ee, DGO)
    for on, rr in ((n, (0, 0, 15, 2)), (s, (0, 13, 15, 15)), (w, (0, 0, 2, 15)), (e, (13, 0, 15, 15))):
        if on:
            t.rect(*rr, GLD)
    if n:
        t.rect(0, 0, 15, 0, K)
        t.rect(0, 3, 15, 3, DRD)
    if s:
        t.rect(0, 15, 15, 15, K)
        t.rect(0, 12, 15, 12, DRD)
    if w:
        t.rect(0, 0, 0, 15, K)
        t.rect(3, 0, 3, 15, DRD)
    if e:
        t.rect(15, 0, 15, 15, K)
        t.rect(12, 0, 12, 15, DRD)
    return t


