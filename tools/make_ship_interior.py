class Tile:
    def __init__(self, bg=None):
        self.g = [[bg] * T for _ in range(T)]

    def px(self, x, y, c):
        if 0 <= x < T and 0 <= y < T:
            self.g[y][x] = c

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.px(x, y, c)

    def frame(self, x0, y0, x1, y1, c):
        self.rect(x0, y0, x1, y0, c)
        self.rect(x0, y1, x1, y1, c)
        self.rect(x0, y0, x0, y1, c)
        self.rect(x1, y0, x1, y1, c)

    def disc(self, cx, cy, r, c):
        for y in range(T):
            for x in range(T):
                if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
                    self.px(x, y, c)

    def transpose(self):
        t = Tile()
        t.g = [[self.g[x][y] for x in range(T)] for y in range(T)]
        return t


def hsh(x, y, s=0):
    return ((x * 73856093) ^ (y * 19349663) ^ (s * 83492791)) % 100


